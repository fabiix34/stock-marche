-- Catalogue des articles lu par l'appli (Supabase > SQL Editor, à exécuter une fois)
create table if not exists articles (
  id        text primary key,                       -- identifiant stable (ne pas changer : lié à l'historique)
  nom       text not null,
  categorie text not null,
  code      int  unique check (code between 1 and 999),
  prix      numeric,                                 -- prix à la pièce ou au kilo selon `unite`
  unite     text not null default 'piece' check (unite in ('piece','kg')),
  actif     boolean not null default true,           -- false = masqué dans l'appli
  ordre     int not null default 0                   -- ordre d'affichage
);
alter table articles enable row level security;
drop policy if exists "acces appli" on articles;
create policy "acces appli" on articles for all using (true) with check (true);
alter publication supabase_realtime add table articles;

